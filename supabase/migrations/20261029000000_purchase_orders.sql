-- Ordens de compra para solicitações de insumos, materiais, serviços e demais itens.
CREATE TABLE IF NOT EXISTS public.purchase_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number TEXT NOT NULL UNIQUE,
  supplier_id BIGINT REFERENCES public.suppliers(id),
  supplier_name TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'solicitado'
    CHECK (status IN ('solicitado', 'aprovado', 'recebido', 'cancelado')),
  expected_date TEXT,
  items TEXT NOT NULL DEFAULT '[]'
    CHECK (jsonb_typeof(items::JSONB) = 'array'),
  notes TEXT NOT NULL DEFAULT '',
  total DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (total >= 0),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_status
  ON public.purchase_orders(status);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_supplier
  ON public.purchase_orders(supplier_id);

ALTER TABLE public.purchase_orders ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.purchase_orders FROM PUBLIC, anon;
REVOKE ALL ON SEQUENCE public.purchase_orders_id_seq FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.purchase_orders TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.purchase_orders_id_seq TO authenticated;

DROP POLICY IF EXISTS purchase_orders_access ON public.purchase_orders;
CREATE POLICY purchase_orders_access ON public.purchase_orders
  FOR ALL TO authenticated
  USING (public.matterdi_has_permission('fornecedores'))
  WITH CHECK (public.matterdi_has_permission('fornecedores'));

-- Libera a tabela somente pela API estruturada já usada pelo aplicativo.
CREATE OR REPLACE FUNCTION matterdi_private.assert_table(table_name TEXT)
RETURNS TEXT LANGUAGE plpgsql IMMUTABLE SET search_path = '' AS $$
BEGIN
  IF table_name IS NULL OR table_name NOT IN (
    'customers', 'products', 'insumos', 'sellers', 'suppliers',
    'employees', 'orders', 'order_items', 'financial',
    'stock_movements', 'pontos', 'holerites', 'materiais', 'maquinas',
    'retalhos', 'composicoes', 'composicao_itens', 'agenda_followups',
    'system_users', 'erp_module_records', 'purchase_orders'
  ) THEN
    RAISE EXCEPTION 'Tabela nao permitida.' USING ERRCODE = '22023';
  END IF;
  RETURN table_name;
END;
$$;
REVOKE ALL ON FUNCTION matterdi_private.assert_table(TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION matterdi_private.assert_table(TEXT) TO authenticated;
