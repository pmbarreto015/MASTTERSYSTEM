-- Expansao ERP v28: registros operacionais separados por permissao de modulo.
-- Aplicavel tambem em projetos existentes; nao altera senhas ou perfis.
CREATE TABLE IF NOT EXISTS public.erp_module_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module TEXT NOT NULL CHECK (module IN ('financeiro', 'rh', 'entregas')),
  record_type TEXT NOT NULL,
  title TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'ativo',
  payload TEXT NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(payload::JSONB) = 'object'),
  reference_id TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE (module, record_type, reference_id)
);
CREATE INDEX IF NOT EXISTS idx_erp_module_type
  ON public.erp_module_records(module, record_type);
ALTER TABLE public.erp_module_records ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.erp_module_records FROM PUBLIC, anon;
REVOKE ALL ON SEQUENCE public.erp_module_records_id_seq FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.erp_module_records TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.erp_module_records_id_seq TO authenticated;

CREATE OR REPLACE FUNCTION public.matterdi_module_allowed(p_module TEXT)
RETURNS BOOLEAN LANGUAGE sql STABLE SECURITY INVOKER SET search_path = '' AS $$
  SELECT CASE p_module
    WHEN 'financeiro' THEN public.matterdi_has_permission('financeiro')
    WHEN 'rh' THEN public.matterdi_has_permission('funcionarios')
    WHEN 'entregas' THEN public.matterdi_has_permission('entregas')
    ELSE FALSE
  END;
$$;
REVOKE ALL ON FUNCTION public.matterdi_module_allowed(TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.matterdi_module_allowed(TEXT) TO authenticated;

DROP POLICY IF EXISTS erp_module_records_select ON public.erp_module_records;
CREATE POLICY erp_module_records_select ON public.erp_module_records FOR SELECT TO authenticated
  USING (public.matterdi_module_allowed(module));
DROP POLICY IF EXISTS erp_module_records_insert ON public.erp_module_records;
CREATE POLICY erp_module_records_insert ON public.erp_module_records FOR INSERT TO authenticated
  WITH CHECK (public.matterdi_module_allowed(module));
DROP POLICY IF EXISTS erp_module_records_update ON public.erp_module_records;
CREATE POLICY erp_module_records_update ON public.erp_module_records FOR UPDATE TO authenticated
  USING (public.matterdi_module_allowed(module))
  WITH CHECK (public.matterdi_module_allowed(module));
DROP POLICY IF EXISTS erp_module_records_delete ON public.erp_module_records;
CREATE POLICY erp_module_records_delete ON public.erp_module_records FOR DELETE TO authenticated
  USING (public.matterdi_module_allowed(module));

-- Mesmo quem pode acessar dois modulos nao pode mover um registro entre eles.
CREATE OR REPLACE FUNCTION public.matterdi_keep_module()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
  v_old_payload JSONB := OLD.payload::JSONB;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.module = 'rh' AND v_old_payload->>'financial_id' IS NOT NULL THEN
      RAISE EXCEPTION 'Preserve o historico: este registro de RH esta vinculado ao financeiro.' USING ERRCODE = '42501';
    END IF;
    RETURN OLD;
  END IF;
  IF NEW.module IS DISTINCT FROM OLD.module THEN
    RAISE EXCEPTION 'O modulo de um registro existente nao pode ser alterado.' USING ERRCODE = '42501';
  END IF;
  IF OLD.module = 'rh' AND v_old_payload->>'financial_id' IS NOT NULL THEN
    IF (NEW.payload::JSONB)->'financial_id' IS DISTINCT FROM v_old_payload->'financial_id'
       OR (NEW.payload::JSONB)->'amount' IS DISTINCT FROM v_old_payload->'amount'
       OR (NEW.payload::JSONB)->'due_date' IS DISTINCT FROM v_old_payload->'due_date'
       OR (NEW.payload::JSONB)->'employee_id' IS DISTINCT FROM v_old_payload->'employee_id' THEN
      RAISE EXCEPTION 'O vinculo financeiro, valor, vencimento e colaborador de RH devem ser preservados. Ajuste a conta no financeiro.' USING ERRCODE = '42501';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_erp_keep_module ON public.erp_module_records;
CREATE TRIGGER trg_erp_keep_module BEFORE UPDATE OR DELETE ON public.erp_module_records
  FOR EACH ROW EXECUTE FUNCTION public.matterdi_keep_module();
REVOKE ALL ON FUNCTION public.matterdi_keep_module() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION matterdi_private.assert_table(table_name TEXT)
RETURNS TEXT LANGUAGE plpgsql IMMUTABLE SET search_path = '' AS $$
BEGIN
  IF table_name IS NULL OR table_name NOT IN (
    'customers', 'products', 'insumos', 'sellers', 'suppliers',
    'employees', 'orders', 'order_items', 'financial',
    'stock_movements', 'pontos', 'holerites', 'materiais', 'maquinas',
    'retalhos', 'composicoes', 'composicao_itens', 'agenda_followups',
    'system_users', 'erp_module_records'
  ) THEN
    RAISE EXCEPTION 'Tabela nao permitida.' USING ERRCODE = '22023';
  END IF;
  RETURN table_name;
END;
$$;
REVOKE ALL ON FUNCTION matterdi_private.assert_table(TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION matterdi_private.assert_table(TEXT) TO authenticated;

