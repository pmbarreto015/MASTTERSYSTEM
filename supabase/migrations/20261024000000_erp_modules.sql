  USING (public.matterdi_has_permission('entregas') AND EXISTS (
    SELECT 1 FROM public.orders AS completed
    WHERE completed.customer_id = customers.id AND completed.tipo = 'OS' AND completed.status = 'entregue'
  ));

-- RLS continua aplicado em ambas as tabelas. A permissao de RH nao basta para
-- criar uma despesa: o mesmo usuario precisa tambem da permissao financeiro.
CREATE OR REPLACE FUNCTION public.matterdi_module_financial(
  p_record_id BIGINT, p_financial JSONB
)
RETURNS JSONB LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE
  v_record public.erp_module_records%ROWTYPE;
  v_payload JSONB;
  v_existing public.financial%ROWTYPE;
  v_financial public.financial%ROWTYPE;
  v_amount DOUBLE PRECISION;
  v_aux DOUBLE PRECISION;
  v_key TEXT;
  v_due TEXT;
  v_now TEXT := to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"');
  v_marker TEXT := '[RH:' || p_record_id::TEXT || ']';
  v_matches INTEGER;
BEGIN
  IF auth.uid() IS NULL OR NOT (
    public.matterdi_has_permission('funcionarios') AND public.matterdi_has_permission('financeiro')
  ) THEN
    RAISE EXCEPTION 'Sem permissao de RH e financeiro para gerar a conta.' USING ERRCODE = '42501';
  END IF;
  SELECT * INTO v_record FROM public.erp_module_records
    WHERE id = p_record_id AND module = 'rh' FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Registro de RH nao encontrado.' USING ERRCODE = 'P0002';
  END IF;
  IF v_record.record_type NOT IN ('folha', 'beneficios', 'rescisoes', 'ferias') THEN
    RAISE EXCEPTION 'Este registro de RH nao gera contas a pagar.' USING ERRCODE = '22023';
  END IF;
  v_payload := v_record.payload::JSONB;
  IF v_payload->>'financial_id' IS NOT NULL THEN
    IF v_payload->>'financial_id' !~ '^[1-9][0-9]*$' THEN
      RAISE EXCEPTION 'Vinculo financeiro invalido.' USING ERRCODE = '22023';
    END IF;
    SELECT * INTO v_existing FROM public.financial
      WHERE id = (v_payload->>'financial_id')::BIGINT;
    IF NOT FOUND OR v_existing.type <> 'pagar' OR position(v_marker IN COALESCE(v_existing.notes, '')) = 0 THEN
      RAISE EXCEPTION 'A conta vinculada foi removida ou nao corresponde ao registro de RH. Confira o historico financeiro.' USING ERRCODE = '22023';
    END IF;
    RETURN to_jsonb(v_existing);
  END IF;
  IF v_record.status <> 'Aprovado' THEN
    RAISE EXCEPTION 'Aprove o registro antes de gerar a conta a pagar.' USING ERRCODE = '22023';
  END IF;
  IF p_financial IS NULL OR jsonb_typeof(p_financial) <> 'object'
     OR p_financial ? 'id'
     OR (p_financial->>'type') IS DISTINCT FROM 'pagar'
     OR (p_financial->>'is_paid') IS DISTINCT FROM '0'
     OR (p_financial->>'status') IS DISTINCT FROM 'pendente'
     OR (p_financial->>'categoria') IS DISTINCT FROM 'pessoal'
     OR NULLIF(trim(p_financial->>'description'), '') IS NULL
     OR position(v_marker IN COALESCE(p_financial->>'notes', '')) = 0 THEN
    RAISE EXCEPTION 'Conta de RH invalida; use despesa pessoal pendente e a referencia do registro.' USING ERRCODE = '22023';
  END IF;
  IF jsonb_typeof(v_payload->'amount') IS DISTINCT FROM 'number'
     OR (v_payload->>'employee_id') IS NULL
     OR (v_payload->>'employee_id') !~ '^[1-9][0-9]*$' THEN
    RAISE EXCEPTION 'Informe o valor aprovado e o colaborador do registro de RH.' USING ERRCODE = '22023';
  END IF;
  v_amount := (v_payload->>'amount')::DOUBLE PRECISION;
  IF v_amount::TEXT IN ('NaN', 'Infinity', '-Infinity') OR v_amount <= 0
     OR (p_financial->>'amount') IS NULL
     OR (p_financial->>'amount')::DOUBLE PRECISION IS DISTINCT FROM v_amount THEN
    RAISE EXCEPTION 'O valor financeiro precisa corresponder ao valor aprovado maior que zero.' USING ERRCODE = '22023';
  END IF;
  v_due := v_payload->>'due_date';
  IF v_due IS NULL OR v_due !~ '^\d{4}-\d{2}-\d{2}'
     OR NULLIF(p_financial->>'due_date', '') IS NULL
     OR (p_financial->>'due_date')::TIMESTAMP IS DISTINCT FROM v_due::TIMESTAMP THEN
    RAISE EXCEPTION 'O vencimento financeiro precisa corresponder ao aprovado no RH.' USING ERRCODE = '22023';
  END IF;
  FOREACH v_key IN ARRAY ARRAY['valor_bruto', 'taxa', 'valor_liquido'] LOOP
    v_aux := COALESCE(NULLIF(p_financial->>v_key, '')::DOUBLE PRECISION, 0);
    IF v_aux::TEXT IN ('NaN', 'Infinity', '-Infinity') OR v_aux < 0 THEN
      RAISE EXCEPTION 'Valores financeiros devem ser finitos e nao negativos.' USING ERRCODE = '22023';
    END IF;
  END LOOP;
  -- Compatibilidade com um envio anterior que gravou a conta antes do vinculo.
  SELECT count(*) INTO v_matches FROM public.financial
    WHERE position(v_marker IN COALESCE(notes, '')) > 0;
  IF v_matches > 1 THEN
    RAISE EXCEPTION 'Ha mais de uma conta com esta referencia de RH. Confira os lancamentos.' USING ERRCODE = '22023';
  ELSIF v_matches = 1 THEN
    SELECT * INTO v_financial FROM public.financial
      WHERE position(v_marker IN COALESCE(notes, '')) > 0;
    IF v_financial.type <> 'pagar' THEN
      RAISE EXCEPTION 'A referencia de RH esta associada a uma conta incompatível.' USING ERRCODE = '22023';
    END IF;
  ELSE
    INSERT INTO public.financial (
      description, amount, type, due_date, is_paid, notes, order_id,
      customer_id, customer_name, categoria, forma_pagamento, parcela,
      total_parcelas, valor_bruto, taxa, valor_liquido, status, pagamentos,
      created_at, updated_at
    ) VALUES (
      p_financial->>'description', v_amount, 'pagar', p_financial->>'due_date', 0,
      p_financial->>'notes', NULL, NULL, NULL, 'pessoal',
      COALESCE(p_financial->>'forma_pagamento', ''),
      COALESCE(NULLIF(p_financial->>'parcela', '')::BIGINT, 0),
      COALESCE(NULLIF(p_financial->>'total_parcelas', '')::BIGINT, 0),
      COALESCE(NULLIF(p_financial->>'valor_bruto', '')::DOUBLE PRECISION, 0),
      COALESCE(NULLIF(p_financial->>'taxa', '')::DOUBLE PRECISION, 0),
      COALESCE(NULLIF(p_financial->>'valor_liquido', '')::DOUBLE PRECISION, 0),
      'pendente', '', v_now, v_now
    ) RETURNING * INTO v_financial;
  END IF;
  UPDATE public.erp_module_records SET
    status = CASE WHEN record_type = 'ferias' THEN status ELSE 'Enviado ao financeiro' END,
    payload = (v_payload || jsonb_build_object(
      'financial_id', v_financial.id, 'financial_sent_at', v_now,
      'financial_sent_by', auth.uid()::TEXT
    ))::TEXT,
    updated_at = v_now
    WHERE id = p_record_id;
  RETURN to_jsonb(v_financial);
END;
$$;
REVOKE ALL ON FUNCTION public.matterdi_module_financial(BIGINT, JSONB) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.matterdi_module_financial(BIGINT, JSONB) TO authenticated;

-- Entregas recebe apenas saldos agregados dos IDs finalizados solicitados.
-- A definer nao retorna descricoes, salarios, outros pedidos ou outros campos.
CREATE OR REPLACE FUNCTION public.matterdi_delivery_balances(p_order_ids JSONB)
RETURNS JSONB LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  v_id JSONB;
  v_ids BIGINT[] := ARRAY[]::BIGINT[];
BEGIN
  IF auth.uid() IS NULL OR NOT public.matterdi_has_permission('entregas') THEN
    RAISE EXCEPTION 'Sem permissao para consultar saldos de entregas.' USING ERRCODE = '42501';
  END IF;
  IF p_order_ids IS NULL OR jsonb_typeof(p_order_ids) <> 'array' THEN
    RAISE EXCEPTION 'Informe uma lista de pedidos.' USING ERRCODE = '22023';
  END IF;
  IF jsonb_array_length(p_order_ids) > 1000 THEN
    RAISE EXCEPTION 'Consulte no maximo 1000 pedidos de cada vez.' USING ERRCODE = '54000';
  END IF;
  FOR v_id IN SELECT value FROM jsonb_array_elements(p_order_ids) LOOP
    IF jsonb_typeof(v_id) <> 'number' OR v_id::TEXT !~ '^[1-9][0-9]*$' THEN
      RAISE EXCEPTION 'ID de pedido invalido.' USING ERRCODE = '22023';
    END IF;
    v_ids := array_append(v_ids, (v_id::TEXT)::BIGINT);
  END LOOP;
  RETURN (SELECT COALESCE(jsonb_agg(to_jsonb(balance) ORDER BY balance.order_id), '[]'::JSONB)
    FROM (
      SELECT completed.id AS order_id,
        COALESCE(SUM(CASE WHEN f.is_paid = 0 THEN f.amount ELSE 0 END), 0) AS pending,
        COALESCE(SUM(f.amount), 0) AS total,
        COALESCE(SUM(CASE WHEN f.is_paid = 1 THEN f.amount ELSE 0 END), 0) AS paid
      FROM public.orders AS completed
      LEFT JOIN public.financial AS f ON f.order_id = completed.id
        AND f.type = 'receber' AND f.status <> 'cancelado'
      WHERE completed.id = ANY(v_ids) AND completed.tipo = 'OS' AND completed.status = 'entregue'
      GROUP BY completed.id
    ) AS balance);
END;
$$;
REVOKE ALL ON FUNCTION public.matterdi_delivery_balances(JSONB) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.matterdi_delivery_balances(JSONB) TO authenticated;

CREATE OR REPLACE FUNCTION public.matterdi_health()
RETURNS JSONB LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT jsonb_build_object(
    'service', 'matterdi-supabase', 'protocol', 1, 'version', 28, 'ready',
      to_regclass('public.system_users') IS NOT NULL
      AND to_regclass('public.erp_module_records') IS NOT NULL
      AND to_regprocedure('public.matterdi_data(jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_report(text,jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_batch(jsonb,boolean,boolean)') IS NOT NULL
      AND to_regprocedure('public.matterdi_is_active_user()') IS NOT NULL
      AND to_regprocedure('public.matterdi_has_permission(text)') IS NOT NULL
      AND to_regprocedure('public.matterdi_order_create(jsonb,jsonb,jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_order_update(bigint,jsonb,jsonb,jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_order_approve(bigint,jsonb,jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_order_delete(bigint)') IS NOT NULL
      AND to_regprocedure('public.matterdi_stock_move(bigint,double precision,text,text,bigint,bigint,bigint,text)') IS NOT NULL
      AND to_regprocedure('public.matterdi_financial_partial(bigint,double precision,text)') IS NOT NULL
      AND to_regprocedure('public.matterdi_financial_from_order(bigint,jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_product_bulk_insert(jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_product_delete_many(jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_agenda_complete_next(bigint,jsonb,jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_composition_save(bigint,jsonb,jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_holerite_save(bigint,jsonb,jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_module_allowed(text)') IS NOT NULL
      AND to_regprocedure('public.matterdi_module_financial(bigint,jsonb)') IS NOT NULL
      AND to_regprocedure('public.matterdi_delivery_balances(jsonb)') IS NOT NULL
  );
$$;
REVOKE ALL ON FUNCTION public.matterdi_health() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.matterdi_health() TO anon, authenticated;
