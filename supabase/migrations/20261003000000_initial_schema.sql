        phone TEXT,
        email TEXT,
        address TEXT,
        observations TEXT,
        total_purchases DOUBLE PRECISION DEFAULT 0,
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL,
        deleted_at TEXT
);
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;

