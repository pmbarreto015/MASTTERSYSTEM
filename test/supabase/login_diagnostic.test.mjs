import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import test from 'node:test';
import { PGlite } from '@electric-sql/pglite';

const sqlPath = fileURLToPath(new URL('../../tool/supabase_diagnosticar_login.sql', import.meta.url));
const userId = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
const otherId = 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
const userEmail = 'diagnostic@example.test';

test('diagnostico de login retorna somente o estado sem alterar contas ou perfis', async (t) => {
  const db = new PGlite();
  await db.waitReady;
  t.after(() => db.close());
  await db.exec(`
    CREATE SCHEMA auth;
    CREATE TABLE auth.users (
      id UUID PRIMARY KEY, email TEXT UNIQUE,
      email_confirmed_at TIMESTAMPTZ, created_at TIMESTAMPTZ DEFAULT now()
    );
    CREATE TABLE public.system_users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT UNIQUE NOT NULL,
      auth_user_id UUID UNIQUE REFERENCES auth.users(id),
      active BIGINT NOT NULL, is_admin BIGINT NOT NULL
    );
  `);
  const source = await readFile(sqlPath, 'utf8');
  const emailFilter = /lower\(email\)\s*=\s*lower\('(?:''|[^'])*'\)/;
  assert.match(source, emailFilter);
  // Substitui somente a copia em memoria, preservando o e-mail do arquivo.
  const sql = source.replace(emailFilter, `lower(email) = lower('${userEmail}')`);

  async function reset({ account = true, confirmed = true } = {}) {
    await db.exec('TRUNCATE public.system_users, auth.users RESTART IDENTITY CASCADE');
    if (account) {
      await db.query(`INSERT INTO auth.users(id, email, email_confirmed_at)
        VALUES ($1, $2, CASE WHEN $3 THEN now() ELSE NULL END)`, [userId, userEmail, confirmed]);
    }
    await db.query('INSERT INTO auth.users(id, email) VALUES ($1, $2)', [otherId, 'other@example.test']);
  }

  async function profile({ username = 'admin', authId = null, active = 1, isAdmin = 1 } = {}) {
    await db.query(`INSERT INTO public.system_users(username, auth_user_id, active, is_admin)
      VALUES ($1, $2, $3, $4)`, [username, authId, active, isAdmin]);
  }

  async function snapshot() {
    return {
      accounts: (await db.query('SELECT * FROM auth.users ORDER BY id')).rows,
      profiles: (await db.query('SELECT * FROM public.system_users ORDER BY id')).rows,
    };
  }

  async function expectStatus(expected) {
    const before = await snapshot();
    // A consulta deve funcionar inclusive em transacao que recusa escritas.
    await db.exec('BEGIN READ ONLY');
    let result;
    try {
      result = await db.query(sql);
    } finally {
      await db.exec('ROLLBACK');
    }
    assert.deepEqual(result.rows, [{ diagnostico: expected }]);
    assert.deepEqual(result.fields.map(field => field.name), ['diagnostico']);
    assert.deepEqual(await snapshot(), before);
  }

  await t.test('conta inexistente e conta nao confirmada precedem perfis', async () => {
    await reset({ account: false });
    await profile({ authId: otherId });
    await expectStatus('EMAIL_NAO_CADASTRADO_NO_AUTH');
    await reset({ confirmed: false });
    await profile({ authId: userId });
    await expectStatus('EMAIL_NAO_CONFIRMADO');
  });

  await t.test('perfil proprio inativo ou ativo precede outros administradores', async () => {
    for (const active of [0, 1]) {
      await reset();
      await profile({ username: 'operador', authId: userId, active, isAdmin: 0 });
      await profile({ authId: otherId });
      await expectStatus(active === 1
        ? 'PERFIL_ATIVO_VERIFICAR_PERMISSOES' : 'CADASTRO_DO_SISTEMA_BLOQUEADO');
    }
  });

  await t.test('admin de outra conta e identificado mesmo inativo e sem privilegio', async () => {
    for (const active of [0, 1]) {
      await reset();
      await profile({ username: 'AdMiN', authId: otherId, active, isAdmin: 0 });
      await expectStatus('ADMIN_VINCULADO_A_OUTRA_CONTA');
    }
  });

  await t.test('outro administrador ativo bloqueia com ou sem vinculo e com admin legado', async () => {
    for (const authId of [null, otherId]) {
      await reset();
      await profile();
      await profile({ username: 'dono', authId });
      await expectStatus('OUTRO_ADMINISTRADOR_ATIVO');
    }
  });

  await t.test('admin legado sem vinculo pode estar ativo ou inativo', async () => {
    for (const active of [0, 1]) {
      await reset();
      await profile({ username: 'AdMiN', active });
      await expectStatus('FALTA_VINCULAR_ADMIN_LEGADO');
    }
  });

  await t.test('banco sem perfil proprio ou admin disponivel requer criar perfil', async () => {
    await reset();
    await expectStatus('FALTA_CRIAR_PERFIL_DO_SISTEMA');
    await profile({ username: 'funcionario', authId: otherId, isAdmin: 0 });
    await profile({ username: 'dono', active: 0 });
    await expectStatus('FALTA_CRIAR_PERFIL_DO_SISTEMA');
  });
});
